import assert from 'node:assert/strict';
import worker from '../../scripts/发布/Cloudflare/worker.mjs';

const reads = [];
const object = { size: 10, httpEtag: '"entity-1"', body: '0123456789', writeHttpMetadata() {} };
const env = { RELEASES: { async get(key, options) { reads.push({ key, options }); return object; }, async head(key) { reads.push({ key }); return object; } } };
let response = await worker.fetch(new Request('https://test.invalid/v1/stable/win-x64/manifest.json'), env);
assert.equal(response.status, 200);
assert.equal(reads[0].key, 'channels/stable/win-x64.json');
assert.equal(response.headers.get('Cache-Control'), 'public, max-age=60');
response = await worker.fetch(new Request(`https://test.invalid/objects/${'a'.repeat(64)}/iSay.zip`), env);
assert.equal(response.headers.get('Cache-Control'), 'public, max-age=31536000, immutable');
assert.equal(response.headers.get('Accept-Ranges'), 'bytes');
object.range = { offset: 3, length: 4 };
object.body = '3456';
response = await worker.fetch(new Request(`https://test.invalid/objects/${'a'.repeat(64)}/iSay.zip`, { headers: { Range: 'bytes=3-6' } }), env);
assert.equal(response.status, 206);
assert.equal(response.headers.get('Content-Range'), 'bytes 3-6/10');
delete object.range;
object.body = '0123456789';
await worker.fetch(new Request(`https://test.invalid/objects/${'a'.repeat(64)}/iSay.zip`, { headers: { Range: 'bytes=3-6', 'If-Range': '"old-entity"' } }), env);
assert.equal(reads.at(-1).options.range.has('range'), false);
await worker.fetch(new Request(`https://test.invalid/objects/${'a'.repeat(64)}/iSay.zip`, { headers: { Range: 'bytes=3-6', 'If-Range': '"entity-1"' } }), env);
assert.equal(reads.at(-1).options.range.get('range'), 'bytes=3-6');
response = await worker.fetch(new Request('https://test.invalid/../private'), env);
assert.equal(response.status, 404);
response = await worker.fetch(new Request('https://test.invalid/v1/stable/win-x64/manifest.json', { method: 'POST' }), env);
assert.equal(response.status, 405);
const missing = { RELEASES: { async get() { return null; } } };
response = await worker.fetch(new Request('https://test.invalid/v1/stable/win-x64/manifest.json'), missing);
assert.equal(response.status, 404);
assert.equal(response.headers.get('Cache-Control'), 'no-store');
console.log('Worker 路由、缓存、范围下载、拒绝未知路径及缺失对象：通过');
